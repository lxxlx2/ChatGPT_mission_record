#!/usr/bin/env python3
"""D1 independent reviewer signature seam, always NON-AUTHORIZING.

An externally approved reviewer key would need to be pinned in a separately
reviewed immutable runtime before any real use. Both pins are deliberately
EMPTY, and there is no live sender, permit issuer, nonce, or production entry.

Unlike the older test_only_trust_roots input, caller data cannot nominate the
review authority here. Tests may temporarily patch the empty pins in an
isolated fixture to exercise fail-closed signature/byte comparisons. This
does NOT enroll a production identity or attest the full runtime closure.
"""
from __future__ import annotations

from hashlib import sha256
import json
from pathlib import Path

from f0_l2_d1_bundle import _strict_permit
from f0_l2_d1_grant import _public_key_fingerprint, _verify_signature
from f0_l2_d1_inventory import (
    installed_ed25519_distribution_inventory_offline,
    tracked_f0_source_manifest_offline,
)

SCHEMA = "bsc-f0-d1-independent-review-reference-OFFLINE-v1"
PINNED_REVIEW_AUTHORITY_KEY_ID = None
PINNED_REVIEW_AUTHORITY_PUBLIC_PEM = None
EXPECTED_FIELDS = frozenset({
    "schema", "reviewer_key_id", "reviewer_public_fingerprint",
    "source_commit_sha", "permit_sha256",
    "tracked_f0_manifest_sha256", "tracked_f0_file_count",
    "wheel_file_manifest_sha256", "cryptography_distribution_version",
    "wheel_file_count", "wheel_entries_without_record_sha256",
    "python_executable_sha256", "complete_runtime_closure_attested",
})


def require(condition, reason):
    if not condition:
        raise ValueError(reason)


def reject_duplicate_json_keys(pairs):
    output = {}
    for key, value in pairs:
        require(key not in output, "D1_REVIEW_DUPLICATE_JSON_FIELD")
        output[key] = value
    return output


def _require_independent_anchor():
    """The default production state is an unconditional DENY."""
    key_id = PINNED_REVIEW_AUTHORITY_KEY_ID
    pem = PINNED_REVIEW_AUTHORITY_PUBLIC_PEM
    require(type(key_id) is str and 8 <= len(key_id) <= 80 and
            type(pem) is bytes and len(pem) <= 4096,
            "D1_REVIEW_AUTHORITY_NOT_ENROLLED")
    return key_id, pem


def reviewer_attestation_message(raw_statement):
    """Sign exact JSON bytes, not re-serialized, mutable parsed values."""
    require(type(raw_statement) is bytes and
            0 < len(raw_statement) <= 8192,
            "D1_REVIEW_STATEMENT_BYTES_INVALID")
    return (SCHEMA + "\n" + sha256(raw_statement).hexdigest() +
            "\n").encode("ascii")


def build_local_review_reference_offline(
        *, permit_raw, checkout_root, reviewed_commit_sha,
        reviewer_key_id, reviewer_public_fingerprint):
    """Return only the measured PARTIAL inventory; never assert full closure.

    Caller-generated bytes are a measurement to be COMPARED against a
    separately signed reference, not a source of review authority.
    """
    permit = _strict_permit(permit_raw)
    require(permit["approved_commit_sha"] == reviewed_commit_sha,
            "D1_REVIEW_PERMIT_COMMIT_MISMATCH")
    tree = tracked_f0_source_manifest_offline(
        checkout_root, reviewed_commit_sha)
    installed = installed_ed25519_distribution_inventory_offline()
    return {
        "schema": SCHEMA,
        "reviewer_key_id": reviewer_key_id,
        "reviewer_public_fingerprint": reviewer_public_fingerprint,
        "source_commit_sha": reviewed_commit_sha,
        "permit_sha256": sha256(permit_raw).hexdigest(),
        "tracked_f0_manifest_sha256":
            tree["tracked_source_manifest_sha256"],
        "tracked_f0_file_count": tree["all_tracked_f0_files_checked"],
        "wheel_file_manifest_sha256":
            installed["wheel_file_manifest_sha256"],
        "cryptography_distribution_version":
            installed["distribution_version"],
        "wheel_file_count": installed["files_read"],
        "wheel_entries_without_record_sha256":
            len(installed["record_entries_without_hash"]),
        "python_executable_sha256":
            installed["python_executable_sha256"],
        "complete_runtime_closure_attested": False,
    }


def verify_independently_signed_reference_offline(
        *, raw_reference, signature, permit_raw, checkout_root):
    """Check an independent key and regenerated exact bytes, never run.

    Only a *separately reviewed code commit* may populate the two PINNED
    constants. There is no caller-supplied trust-root argument. With the
    constants empty this always fails closed before any work. Even a PASS
    verifies only the listed partial local inventory and cannot authorize
    HTTPS, a real grant, or consumption of a production registry marker.
    """
    key_id, pem = _require_independent_anchor()
    require(type(raw_reference) is bytes and
            0 < len(raw_reference) <= 8192 and
            type(signature) is bytes and len(signature) == 64 and
            type(permit_raw) is bytes and
            isinstance(checkout_root, Path) and
            checkout_root.is_absolute(),
            "D1_REVIEW_ARGUMENT_INVALID")
    try:
        parsed = json.loads(raw_reference,
                            object_pairs_hook=reject_duplicate_json_keys)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError("D1_REVIEW_REFERENCE_JSON_INVALID") from exc
    require(type(parsed) is dict and set(parsed) == EXPECTED_FIELDS
            and parsed.get("schema") == SCHEMA
            and parsed.get("complete_runtime_closure_attested") is False,
            "D1_REVIEW_UNREVIEWED_FIELDS_OR_FALSE_CLOSURE")
    fingerprint = _public_key_fingerprint(pem)
    require(parsed["reviewer_key_id"] == key_id and
            parsed["reviewer_public_fingerprint"] == fingerprint,
            "D1_REVIEW_INDEPENDENT_AUTHORITY_ID_MISMATCH")
    # Verify signature BEFORE trusting the manifest as reviewer evidence.
    require(_verify_signature(
        pem, reviewer_attestation_message(raw_reference), signature),
        "D1_REVIEW_SIGNATURE_INVALID")
    expected = build_local_review_reference_offline(
        permit_raw=permit_raw, checkout_root=checkout_root,
        reviewed_commit_sha=parsed["source_commit_sha"],
        reviewer_key_id=key_id,
        reviewer_public_fingerprint=fingerprint)
    require(parsed == expected,
            "D1_REVIEW_SIGNED_REFERENCE_DOES_NOT_MATCH_RUNTIME")
    return {
        "status": "OFFLINE_INDEPENDENT_REFERENCE_MATCH_PARTIAL_ONLY",
        "reviewed_commit_sha": expected["source_commit_sha"],
        "reference_sha256": sha256(raw_reference).hexdigest(),
        "tracked_f0_file_count": expected["tracked_f0_file_count"],
        "wheel_file_count": expected["wheel_file_count"],
        "wheel_record_unhashed": expected[
            "wheel_entries_without_record_sha256"],
        "complete_runtime_closure_attested": False,
        "production_user_identity_verified": False,
        "production_user_consent_verified": False,
        "grant_consumed": False,
        "actual_rpc_requests": 0,
        "live_sender_authorized": False,
    }
